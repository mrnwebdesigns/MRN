#!/usr/bin/env python3
"""Tests for the mrndev site-owner AuthorizedKeysCommand.

The command is generated by stack/server-config/mrndev/install-site-owner-authorized-keys-command.sh.
These tests extract it, point its fixed paths at a temporary directory, and run it against a
fake CloudPanel database. sshd runs the real command as root, so "owned by this process's
user" (bash -O) stands in for "owned by root" here.
"""

from __future__ import annotations

import os
import shutil
import sqlite3
import stat
import subprocess
import tempfile
import unittest
from pathlib import Path

INSTALLER = Path(__file__).resolve().parents[1] / "server-config/mrndev/install-site-owner-authorized-keys-command.sh"
SHARED_KEY = "ssh-ed25519 AAAASHARED mrn-site-owner"
DEPLOY_KEY = "ssh-ed25519 AAAADEPLOY github-actions-deploy"


def extract_command() -> str:
    text = INSTALLER.read_text()
    start = text.index("<<'SCRIPT'\n") + len("<<'SCRIPT'\n")
    end = text.index("\nSCRIPT\n", start)
    return text[start:end] + "\n"


@unittest.skipUnless(shutil.which("sqlite3") and shutil.which("bash"), "needs sqlite3 and bash")
class SiteOwnerAuthorizedKeysCommandTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        self.db = self.tmp / "db.sq3"
        con = sqlite3.connect(self.db)
        con.execute("CREATE TABLE site (user TEXT)")
        con.execute("CREATE TABLE ssh_user (user_name TEXT)")
        con.execute("INSERT INTO site VALUES ('mrnwebdesigns-stack')")
        con.execute("INSERT INTO ssh_user VALUES ('kapil-mrnwebdesigns')")
        con.commit()
        con.close()
        self.shared = self.tmp / "site-owner-authorized-key.pub"
        self.shared.write_text(SHARED_KEY + "\n")
        self.keys = self.tmp / "mrn-site-deploy-keys"
        self.keys.mkdir(mode=0o755)
        os.chmod(self.keys, 0o755)
        self.write_deploy_key("mrnwebdesigns-stack")

        bin_dir = self.tmp / "bin"
        bin_dir.mkdir()
        getent = bin_dir / "getent"
        getent.write_text(
            "#!/bin/sh\n"
            "case \"$2\" in mrnwebdesigns-stack|kapil-mrnwebdesigns|other-site) echo \"$2:x:1:1::/home/$2:/bin/bash\";; *) exit 2;; esac\n"
        )
        getent.chmod(0o755)
        self.env = {**os.environ, "PATH": f"{bin_dir}:{os.environ['PATH']}"}

        command = extract_command()
        for old, new in (
            ("/home/clp/htdocs/app/data/db.sq3", str(self.db)),
            ("/home/mrndev-stack-manager/stack/configs/site-owner-authorized-key.pub", str(self.shared)),
            ("/etc/ssh/mrn-site-deploy-keys", str(self.keys)),
        ):
            self.assertIn(old, command)
            command = command.replace(old, new)
        self.command = self.tmp / "mrn-site-owner-authorized-keys"
        self.command.write_text(command)
        self.command.chmod(0o755)

    def write_deploy_key(self, user: str, mode: int = 0o644) -> Path:
        path = self.keys / f"{user}.pub"
        path.write_text(DEPLOY_KEY + "\n")
        os.chmod(path, mode)
        return path

    def run_for(self, user: str) -> list[str]:
        result = subprocess.run(
            ["bash", str(self.command), user], env=self.env, capture_output=True, text=True, check=True
        )
        return [line for line in result.stdout.splitlines() if line]

    def test_site_owner_gets_shared_and_deploy_key(self) -> None:
        self.assertEqual(self.run_for("mrnwebdesigns-stack"), [SHARED_KEY, DEPLOY_KEY])

    def test_cloudpanel_ssh_user_gets_shared_key_but_never_a_deploy_key(self) -> None:
        self.write_deploy_key("kapil-mrnwebdesigns")
        self.assertEqual(self.run_for("kapil-mrnwebdesigns"), [SHARED_KEY])

    def test_deploy_key_still_served_without_shared_key(self) -> None:
        self.shared.unlink()
        self.assertEqual(self.run_for("mrnwebdesigns-stack"), [DEPLOY_KEY])

    def test_group_or_world_writable_deploy_key_is_ignored(self) -> None:
        for mode in (0o664, 0o646):
            with self.subTest(mode=oct(mode)):
                self.write_deploy_key("mrnwebdesigns-stack", mode)
                self.assertEqual(self.run_for("mrnwebdesigns-stack"), [SHARED_KEY])

    def test_writable_key_directory_is_ignored(self) -> None:
        os.chmod(self.keys, 0o775)
        self.assertEqual(self.run_for("mrnwebdesigns-stack"), [SHARED_KEY])

    def test_symlinked_deploy_key_is_ignored(self) -> None:
        target = self.tmp / "elsewhere.pub"
        target.write_text(DEPLOY_KEY + "\n")
        link = self.keys / "mrnwebdesigns-stack.pub"
        link.unlink()
        link.symlink_to(target)
        self.assertEqual(self.run_for("mrnwebdesigns-stack"), [SHARED_KEY])

    def test_unknown_reserved_and_malformed_users_get_nothing(self) -> None:
        for user in ("other-site", "root", "kyle", "../etc", "Mrnwebdesigns-stack", "a", ""):
            with self.subTest(user=user):
                self.assertEqual(self.run_for(user), [])

    def test_installer_creates_root_owned_key_directory(self) -> None:
        text = INSTALLER.read_text()
        self.assertIn('install -d -o root -g root -m 755 "${DEPLOY_KEY_DIR}"', text)
        self.assertEqual(stat.S_IMODE(os.stat(self.keys).st_mode) & 0o022, 0)


if __name__ == "__main__":
    unittest.main()
